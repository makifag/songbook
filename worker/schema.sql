CREATE TABLE IF NOT EXISTS hidden (slug TEXT PRIMARY KEY, at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS marks (slug TEXT PRIMARY KEY, d INTEGER NOT NULL DEFAULT 0, f INTEGER NOT NULL DEFAULT 0, at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS wish (id INTEGER PRIMARY KEY AUTOINCREMENT, text TEXT NOT NULL, url TEXT NOT NULL DEFAULT '', at TEXT NOT NULL);
